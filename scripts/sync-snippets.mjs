import { readFile, writeFile, readdir, stat } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { resolve, relative } from 'node:path';
import { verifyEvidence } from './snippet-evidence.mjs';
const root = resolve(import.meta.dirname, '..');
const project = resolve(root, 'examples/order-service');
async function fingerprint() {
  async function walk(dir) {
    const result = [];
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      const path = resolve(dir, entry.name);
      if (entry.isSymbolicLink()) throw new Error('Source symlinks are not supported');
      if (entry.isDirectory()) result.push(...await walk(path));
      else result.push(path);
    }
    return result;
  }
  const files = [...await walk(resolve(project, 'src')), resolve(project, 'pom.xml'), resolve(root, 'scripts/java-lab.sh')].sort();
  const hash = createHash('sha256');
  for (const file of files) hash.update(relative(root, file)).update('\0').update(await readFile(file)).update('\0');
  return hash.digest('hex');
}
const before = await fingerprint();
const startedAt = Date.now();
// Always clean-compile and test: a prior report cannot certify newly edited code.
const run = spawnSync(resolve(root, 'scripts/java-lab.sh'), ['verify', '-q'],
  { cwd:root, encoding:'utf8', timeout:300000, maxBuffer:2*1024*1024 });
if (run.error || run.status !== 0) throw new Error('Java verification failed; run java-lab.sh verify for diagnostics');
const reportPath = resolve(project, 'target/surefire-reports/TEST-dev.agentesnamedida.orders.OrderCliTest.xml');
const counts = verifyEvidence({ before, after:await fingerprint(), exitCode:run.status,
  startedAt, reportTime:(await stat(reportPath)).mtimeMs, report:await readFile(reportPath,'utf8') });
const source = 'examples/order-service/src/main/java/dev/agentesnamedida/orders/OrderRepository.java';
const java = await readFile(resolve(root, source), 'utf8');
const snippet = java.match(/    public List<Order> search\([\s\S]*?\n    }/);
if (!snippet || before !== await fingerprint()) throw new Error('Sources changed or search method missing');
const content = {
  source, sourceSha256:createHash('sha256').update(java).digest('hex'), verifiedSourceTreeSha256:before,
  javaSnippet:snippet[0].split('\n').map(line=>line.replace(/^    /,'')).join('\n'),
  focusedCommand: "mvn -q '-Dtest=OrderCliTest#searchReturnsTopFive*' test",
  tests:{ executed:counts.executed, failures:0, errors:0, skipped:0 }
};
await writeFile(resolve(root,'docs/data/verified-code.js'),
  '// Generated by scripts/sync-snippets.mjs after a fresh clean Java verification.\nwindow.VERIFIED_CODE = Object.freeze('+JSON.stringify(content,null,2)+');\n');
console.log(JSON.stringify({source, sourceSha256:content.sourceSha256, verifiedSourceTreeSha256:before, tests:content.tests}));
